  f"assigned to an A–B ({V['eq_nA']} students) or B–A ({V['eq_nB']} students) sequence, so no item was repeated for any "
  "student. Raw scores ranged from 0 to 40. Testing was proctored, computer-based and simultaneous in two adjacent halls, "
