  f"using the baseline random groups: Form A mean {V['eq_mA']:.2f} (SD {V['eq_sA']:.2f}) and Form B mean {V['eq_mB']:.2f} "
  f"(SD {V['eq_sB']:.2f}). Calculated from unrounded values, the transformation was equated B = {V['eq_slope']:.3f} × raw "
  f"B + {V['eq_icpt']:.3f}. It was applied unchanged to follow-up Form B scores, and Form A scores were not transformed. The "
  f"transformation maps raw scores of 0–40 to {V['eq_icpt']:.2f}–{40 * V['eq_slope'] + V['eq_icpt']:.2f}, so no truncation "
  "was required. All knowledge analyses used reference-form scores, and the sensitivity analyses included test-form "
